#!/usr/bin/env node
// Regenerates src/mastra/integrations/studio/template-manifest.ts from the human-editable template
// source files under src/mastra/integrations/studio/templates/{webapp,mcp}/**.
//
// Why this exists: Mastra's build only bundles statically-imported JS/TS modules — a plain directory
// of template files under src/ that's only read via fs at runtime does NOT survive `mastra build`
// (verified: it never appears in .mastra/output). Embedding the file contents as string constants
// makes them genuine bundled values instead of a filesystem asset, so they exist wherever
// template-seed.ts runs (including production).
//
// Run this after editing anything under templates/webapp/ or templates/mcp/, then commit the
// regenerated template-manifest.ts alongside your template changes:
//   node scripts/generate-studio-templates.mjs
import { readdirSync, statSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const STUDIO_DIR = join(ROOT, 'src/mastra/integrations/studio');
const WEBAPP_DIR = join(STUDIO_DIR, 'templates/webapp');
const MCP_DIR = join(STUDIO_DIR, 'templates/mcp');
const OUT_FILE = join(STUDIO_DIR, 'template-manifest.ts');

function walk(dir, base = dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) out.push(...walk(full, base));
    else out.push(relative(base, full).split('\\').join('/')); // POSIX-style keys on any OS
  }
  return out.sort();
}

function buildManifestEntries(templateDir) {
  return walk(templateDir)
    .map((relPath) => {
      const content = readFileSync(join(templateDir, relPath), 'utf8');
      return `  ${JSON.stringify(relPath)}: ${JSON.stringify(content)},`;
    })
    .join('\n');
}

const output = `// AUTO-GENERATED by scripts/generate-studio-templates.mjs — DO NOT hand-edit.
// Edit the source files under templates/webapp/** or templates/mcp/**, then re-run:
//   node scripts/generate-studio-templates.mjs
//
// Mastra's build only bundles statically-imported JS/TS modules; arbitrary files under src/ that are
// only read via fs at runtime do NOT survive \`mastra build\` (verified: they never appear in
// .mastra/output). Embedding the template files as string constants makes them genuine bundled
// values instead of a filesystem asset, so they always exist wherever this module is imported.

/** path (relative to the project root) -> file content */
export const WEBAPP_TEMPLATE_FILES: Record<string, string> = {
${buildManifestEntries(WEBAPP_DIR)}
};

/** path (relative to the project root) -> file content */
export const MCP_TEMPLATE_FILES: Record<string, string> = {
${buildManifestEntries(MCP_DIR)}
};
`;

writeFileSync(OUT_FILE, output);
console.log(`Wrote ${relative(ROOT, OUT_FILE)}`);
